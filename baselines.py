"""
Baseline models for storm prediction paper.

Requires data/cmip6_world/train_data_idxs.npy and test_data_idxs.npy
generated by save_data_indices.py (uses exact same samples as the model).

Baseline 1 (Climatological): score = sfcWindmax / q95_historical_per_cell
Baseline 2 (LR): LogisticRegression on 4 point-in-time CMIP6 values

Train: 2000-2020  |  Test: 2023-2024
"""
import logging
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score, average_precision_score, brier_score_loss
from sklearn.preprocessing import StandardScaler

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger(__name__)

DATA_DIR  = "data/cmip6_world"
TRAIN_END = np.datetime64("2021-01-01")


# ---------------------------------------------------------------------------
# 1. Load pre-computed indices (same samples as the model)
# ---------------------------------------------------------------------------
log.info("Loading data indices ...")
train_idxs = np.load(f"{DATA_DIR}/train_data_idxs.npy")  # (15+, N_train)
test_idxs  = np.load(f"{DATA_DIR}/test_data_idxs.npy")   # (15+, N_test)
log.info(f"train: {train_idxs.shape[1]}  test: {test_idxs.shape[1]}")

# Indices: row0=lat, row1=lon, row2=time, row7=y(m/s), row14=station_threshold
# Indices in the saved array are padded (shift = half_side_size = 47).
# Subtract shift to recover original CMIP6 grid indices (0-159 lat, 0-319 lon).
HALF_SIDE = 47
lat_tr = (train_idxs[0].astype(int) - HALF_SIDE).clip(0, 159)
lon_tr = (train_idxs[1].astype(int) - HALF_SIDE).clip(0, 319)
time_tr = train_idxs[2].astype(int)
lat_te = (test_idxs[0].astype(int) - HALF_SIDE).clip(0, 159)
lon_te = (test_idxs[1].astype(int) - HALF_SIDE).clip(0, 319)
time_te = test_idxs[2].astype(int)

y_tr    = train_idxs[7].astype(np.float32)
y_te    = test_idxs[7].astype(np.float32)
thr_tr  = train_idxs[8].astype(np.float32)
thr_te  = test_idxs[8].astype(np.float32)

binary_tr = (y_tr >= thr_tr).astype(np.int8)
binary_te = (y_te >= thr_te).astype(np.int8)

log.info(f"Train positive rate: {binary_tr.mean():.3f}")
log.info(f"Test  positive rate: {binary_te.mean():.3f}")


# ---------------------------------------------------------------------------
# 2. Load CMIP6 variables (float16 → float32)
# ---------------------------------------------------------------------------
log.info("Loading CMIP6 variables ...")
time_grid = np.load(f"{DATA_DIR}/time.npy").astype("datetime64[D]")
sfcWindmax = np.load(f"{DATA_DIR}/sfcWindmax_16.npy").astype(np.float32)
pr         = np.load(f"{DATA_DIR}/pr_16.npy").astype(np.float32)
tasmax     = np.load(f"{DATA_DIR}/tasmax_16.npy").astype(np.float32)
tasmin     = np.load(f"{DATA_DIR}/tasmin_16.npy").astype(np.float32)
elev       = np.load(f"{DATA_DIR}/elev_16.npy").astype(np.float32)   # (lat, lon)
log.info(f"sfcWindmax shape: {sfcWindmax.shape}")


# ---------------------------------------------------------------------------
# 3. Climatological q95 per grid cell (train period only)
# Note: data is float16-normalized, so q95 is in normalized units — still
# works as a relative score (higher = more wind relative to history).
# ---------------------------------------------------------------------------
log.info("Computing climatological q95 (train period) ...")
train_time_mask = time_grid < TRAIN_END
q95_grid = np.quantile(sfcWindmax[train_time_mask], 0.95, axis=0)  # (lat, lon)
log.info(f"q95 range: {q95_grid.min():.3f} .. {q95_grid.max():.3f}")

# Climatological score: sfcWindmax / q95  (> 1 → exceeds climatology)
clim_score_te = sfcWindmax[time_te, lat_te, lon_te] / np.maximum(q95_grid[lat_te, lon_te], 1e-3)


# ---------------------------------------------------------------------------
# 4. LR features: 4 CMIP6 point-in-time values
# ---------------------------------------------------------------------------
log.info("Extracting LR features ...")
def feat(ti, lai, loi):
    return np.column_stack([
        sfcWindmax[ti, lai, loi],
        pr        [ti, lai, loi],
        tasmax    [ti, lai, loi],
        tasmin    [ti, lai, loi],
        elev      [lai, loi],        # static, no time dimension
    ])

X_train = feat(time_tr, lat_tr, lon_tr)
X_test  = feat(time_te, lat_te, lon_te)
log.info(f"X_train: {X_train.shape}  X_test: {X_test.shape}")


# ---------------------------------------------------------------------------
# 5. Train LR
# ---------------------------------------------------------------------------
log.info("Training Logistic Regression ...")
scaler = StandardScaler()
X_tr_s = scaler.fit_transform(X_train)
X_te_s = scaler.transform(X_test)

lr = LogisticRegression(max_iter=1000, C=1.0, n_jobs=-1)
lr.fit(X_tr_s, binary_tr)
lr_score = lr.predict_proba(X_te_s)[:, 1]
log.info("LR trained.")


# ---------------------------------------------------------------------------
# 6. Evaluate
# ---------------------------------------------------------------------------
def metrics(name, y_true, y_score):
    y_score = np.clip(y_score.astype(np.float64), 0, 1)
    y_true  = y_true.astype(int)
    auroc = roc_auc_score(y_true, y_score)
    ap    = average_precision_score(y_true, y_score)
    bs    = brier_score_loss(y_true, y_score)
    p_c   = float(y_true.mean())
    bss   = 1.0 - bs / (p_c * (1.0 - p_c))
    log.info(f"{name:45s}  AUROC={auroc:.4f}  AP={ap:.4f}  BS={bs:.4f}  BSS={bss:.4f}")
    return {"AUROC": auroc, "AP": ap, "BS": bs, "BSS": bss}

log.info("=" * 70)
metrics("Climatological (sfcWindmax/q95_hist)", binary_te, clim_score_te)
metrics("LR (sfcWindmax, pr, tasmax, tasmin, elev)", binary_te, lr_score)
log.info("=" * 70)
log.info("Done.")
